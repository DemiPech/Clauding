const TYPE_LABELS = {
  Action: 'Actions',
  'Attack Reaction': "Réactions d'attaque",
  'Defense Reaction': 'Réactions de défense',
  Instant: 'Instants',
  Block: 'Blocs',
  Resource: 'Ressources',
};

const TYPE_ORDER = [
  'Attaques',
  'Actions',
  "Réactions d'attaque",
  'Réactions de défense',
  'Blocs',
  'Instants',
  'Ressources',
];

// Couleurs de location CardNexus → pastille de la carte de deck.
const LOCATION_COLORS = {
  red: '#c0392b',
  green: '#3f9e5a',
  blue: '#3b7bc4',
  yellow: '#d9a520',
  white: '#cfc6ba',
  black: '#5a534b',
};

function typeLabel(card) {
  if (card.subtypes.includes('Attack')) return 'Attaques';
  const primary = card.types[0];
  return TYPE_LABELS[primary] || primary || 'Autres';
}

/** Une liste de deck (FaBrary ou decklist fabtcg.com), par opposition à l'inventaire. */
const isListSource = (source) => source === 'fabrary' || source === 'fabtcg';

const escapeHtml = (text) =>
  String(text).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);

export {
  LOCATION_COLORS, PITCH_COLORS, PITCH_LABELS, TYPE_ORDER, els, escapeHtml, state, typeLabel, isListSource,
};
